const fs=require('node:fs'),path=require('node:path');
const {youtubeStart}=require('../shared/youtube-start.cjs');
const {mediaStart}=require('../shared/media-start.cjs');
function sync() {
 const root=path.resolve(__dirname,'..');
 const generated='// Generated by tools/sync-page-scripts.cjs; edit shared/*-start.cjs.\n';
 const preload=generated+`const {contextBridge,ipcRenderer}=require('electron');
const policy=ipcRenderer.sendSync('page-start-policy');
if(policy){
 contextBridge.executeInMainWorld({func:${mediaStart.toString()}});
 if(policy.youtube)contextBridge.executeInMainWorld({func:${youtubeStart.toString()}});
 for(const type of ['pointerdown','keydown'])document.addEventListener(type,e=>{if(e.isTrusted)ipcRenderer.send('page-media-activate');},true);
}
`;
 fs.writeFileSync(path.join(root,'desktop/page-preload.cjs'),preload);
 const assets=path.join(root,'android/app/src/main/assets');fs.mkdirSync(assets,{recursive:true});
 fs.writeFileSync(path.join(assets,'youtube-start.js'),generated+`(${youtubeStart.toString()})();\n`);
 fs.writeFileSync(path.join(assets,'media-start.js'),generated+`(${mediaStart.toString()})();\n`);
 const extension=path.join(assets,'sukoaa-policy');fs.mkdirSync(extension,{recursive:true});
 fs.writeFileSync(path.join(extension,'youtube-start.js'),generated+`(${youtubeStart.toString()})();\n`);
 fs.writeFileSync(path.join(extension,'media-start.js'),generated+`(${mediaStart.toString()})();\n`);
 fs.writeFileSync(path.join(extension,'manifest.json'),JSON.stringify({manifest_version:3,name:'Sukoaa page policy',version:'1.1.0',browser_specific_settings:{gecko:{id:'page-policy@sukoaa.local'}},content_scripts:[{matches:['https://*.youtube.com/*'],js:['youtube-start.js'],run_at:'document_start',world:'MAIN'},{matches:['https://*/*'],js:['media-start.js'],run_at:'document_start',world:'MAIN',all_frames:true}]},null,2)+'\n');
}
if(require.main===module)sync();module.exports={sync};
